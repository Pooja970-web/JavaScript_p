//Loops in Java are used to execute a block of code repeatedly until a condition becomes false 
// or a specified number of iterations is completed.
/*Types of loops in Java

Java has four commonly used loop structures:

1. for loop

Use it when you know how many times you want to repeat something.




2. while loop

Use it when repetition depends on a condition.




3. do-while loop

Executes the code at least once before checking the condition.




4. for...of loop

Use for...of to iterate over the values of an array or another iterable.*/