//Parameters let a function accept input.
//Parameter: name — the variable listed in the function definition.
//Argument: "Pooja" — the actual value passed when calling the function.
//You can use multiple parameters

function greet(name,course){
    console.log("Hello" +name + ", you are enrolled in " + course);
}
greet("Pooja"); // Output: Hello Pooja
greet("Pooja","JavaScript"); // Output: Hello Pooja, you are enrolled in JavaScript
